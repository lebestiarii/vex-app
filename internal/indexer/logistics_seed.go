// SeedLogisticsDemoPack writes all logistics reference collections to dataDir
// and returns the total number of cards written.
func SeedLogisticsDemoPack(dataDir string) (int, error) {
	collections := LogisticsDemoCollections()
	total := 0
	for col, cards := range collections {
		if _, err := SaveCollectionFile(dataDir, col, cards); err != nil {
			return total, fmt.Errorf("write logistics collection %q: %w", col, err)
		}
		total += len(cards)
	}
	return total, nil
}
